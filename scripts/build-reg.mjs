import { cp, mkdir, readFile, writeFile, readdir, rm, stat } from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = fileURLToPath(new URL('../', import.meta.url));
const output = path.join(root, 'dist-reg');
const marker = '.generated-reg-package';
// This directory is a disposable package, never the location of a working installation.
if (path.dirname(output) !== path.resolve(root) || path.basename(output) !== 'dist-reg') throw new Error('Unsafe build path');
let exists = false;
try { await stat(output); exists = true; } catch (error) { if (error.code !== 'ENOENT') throw error; }
if (exists) {
  try { await readFile(path.join(output, marker)); }
  catch { throw new Error('Refusing to overwrite an unrecognized dist-reg directory'); }
  await rm(output, { recursive: true });
}
const site = path.join(output, 'site');
const privateRoot = path.join(output, 'vosem-utra-private');
const app = path.join(privateRoot, 'app');
await mkdir(path.join(app, 'templates'), { recursive: true });
await writeFile(path.join(output, marker), 'Generated by scripts/build-reg.mjs; do not store working data here.\n');
const built = path.join(root, 'dist-hosting');
const manifest = JSON.parse(await readFile(path.join(built, 'site-build.json'), 'utf8'));
if (!manifest.production || manifest.siteUrl !== 'https://vosem-utra.ru/') throw new Error('First run npm run build:hosting');
await cp(built, site, { recursive: true });
await cp(path.join(root, 'hosting/legacy-public'), site, { recursive: true });
await cp(path.join(root, 'hosting/legacy-private'), privateRoot, { recursive: true });
await cp(path.join(root, 'hosting/php'), app, { recursive: true });
await cp(path.join(root, 'hosting/public'), site, { recursive: true });
// Old registration pages reference these stable local asset URLs.
await cp(path.join(root, 'assets'), path.join(site, 'assets'), { recursive: true });
await cp(path.join(root, 'style.css'), path.join(site, 'style.css'));
await cp(path.join(root, 'site.js'), path.join(site, 'site.js'));
await mkdir(path.join(app, 'seed'), { recursive: true });
await cp(path.join(root, 'public/data/menu.json'), path.join(app, 'seed/menu.json'));
for (const page of ['index', 'admin', 'registration', 'privacy', 'consent', 'checkout', 'order-terms']) {
  let html = await readFile(path.join(site, `${page}.html`), 'utf8');
  // The current homepage already includes cookies.js and its settings button.
  // Vite bundles that module: injecting the legacy URL too creates two banners.
  await writeFile(path.join(app, 'templates', `${page}.html`), html);
  // HTML pages must pass through PHP (fresh menu, nonce, noindex); never leave a static bypass.
  await rm(path.join(site, `${page}.html`));
}
// Public JSON also passes through PHP and cannot leak a hidden seed item.
await rm(path.join(site, 'data'), { recursive: true, force: true });
await rm(path.join(site, 'site-build.json'), { force: true });
await rm(path.join(site, 'robots.txt'), { force: true });
await rm(path.join(site, 'sitemap.xml'), { force: true });
await writeFile(path.join(privateRoot, '.htaccess'), 'Require all denied\n');
await cp(path.join(root, 'hosting/admin-config.example.php'), path.join(privateRoot, 'admin-config.example.php'));
await cp(path.join(root, 'hosting/orders-config.example.php'), path.join(privateRoot, 'orders-config.example.php'));
await cp(path.join(root, 'hosting/prepare-access.php'), path.join(privateRoot, 'prepare-access.php'));
await cp(path.join(root, 'docs/reg-upload.md'), path.join(output, 'READ-ME.md'));
await cp(path.join(root, 'docs/delivery.md'), path.join(output, 'delivery.md'));
// A package never includes runtime data or the old integration credentials.
for (const name of ['admin-config.php', 'admin-data', 'orders-config.php', 'order-data', 'orders-data', 'loyalty.php', 'recaptcha.php', 'consents']) {
  if ((await readdir(privateRoot)).includes(name)) throw new Error(`Private runtime content leaked into package: ${name}`);
}
console.log('REG.RU package ready: dist-reg/site + dist-reg/vosem-utra-private (no passwords or integration keys).');
