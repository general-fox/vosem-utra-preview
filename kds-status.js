// Only a server-confirmed Accepted state means that KDS accepted the order.
export function kdsStatusView(delivery) {
  const states = {
    queued: ['Готовим отправку', 'Заявка сохранена. Проверяем блюда и отправляем в тестовую КДС.', true],
    preparing: ['Проверяем блюда', 'Сверяем цены и наличие с тестовой КДС.', true],
    sending: ['Ожидаем ответ КДС', 'Отправка началась. Дождитесь результата.', true],
    Pending: ['Ожидает принятия в КДС', 'Заявка поступила в КДС. Ожидаем, когда сотрудник примет её в работу.', true],
    Accepted: ['Принят в КДС', 'КДС подтвердила принятие, заказ передан в кассу.', true],
    Ready: ['Готов по данным КДС', 'КДС сообщила о готовности тестового заказа.', true],
    Closed: ['Завершён в КДС', 'Тестовый заказ закрыт в кассе.', false],
    Canceled: ['Отменён в КДС', 'Заявка отменена. Повторная отправка не выполняется.', false],
    blocked: ['Не отправлен в КДС', 'Проверка перед отправкой не прошла. Проверьте подключение, цены и доступность блюд в КДС.', false],
    missing: ['Заявка не найдена в КДС', 'КДС не нашла эту заявку. Перед новым заказом уточните результат у сотрудника.', false],
    unknown: ['Результат отправки пока неизвестен', 'Ответ на отправку не получен. Чтобы не создать дубль, повторная отправка остановлена. Проверьте заявку у сотрудника КДС.', false],
    not_connected: ['Сохранено на тестовом стенде', 'Для этой заявки передача в КДС не подключена.', false],
  };
  const [title, description, poll] = states[delivery?.state] || ['Проверяем состояние', 'Ожидаем подтверждённый статус от сервера.', true];
  const issue = delivery?.issue === 'acceptance_error' ? ' В КДС возникла ошибка принятия; проверьте её на рабочем месте сотрудника.' : delivery?.issue === 'connection_unavailable' ? ' Связь с КДС временно недоступна; проверка продолжится.' : '';
  return { title, description: description + issue, poll };
}
export function trackingIdFromHash(hash) { return /^#order=([a-f0-9]{32})$/.exec(hash)?.[1] || null; }
